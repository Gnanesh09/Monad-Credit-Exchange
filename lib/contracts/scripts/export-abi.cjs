// Writes the compiled ABIs to src/generated/abis.ts as const arrays so viem and
// wagmi infer argument and return types.
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const contracts = [
  { name: "CitrineExchange", file: "CitrineExchange.sol", exportName: "citrineExchangeAbi" },
  { name: "FaucetToken", file: "FaucetToken.sol", exportName: "faucetTokenAbi" },
];

let out = "// Generated by scripts/export-abi.cjs from the Hardhat build. Do not edit.\n\n";
for (const c of contracts) {
  const artifactPath = path.join(root, "artifacts", "contracts", c.file, `${c.name}.json`);
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  out += `export const ${c.exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}

const target = path.join(root, "src", "generated", "abis.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`Wrote ${path.relative(root, target)}`);
